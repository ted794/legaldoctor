def deck_html(d: dict) -> str:
    tag = '<div class="tag">가상 예시 · 규제팡 시연용</div>'
    foot = f'<div class="foot">{e(d["company"])} · 모든 회사·서비스·수치는 가상입니다</div>'
    out = [f'<section class="s cover">{tag}<h1>{e(d["title"])}</h1><p>{e(d["one"])}</p><div class="co">{e(d["company"])} 사업소개서</div></section>']
    for i, (h, items) in enumerate(d["pages"]):
        out.append(f'<section class="s">{tag}<h2>{e(h)}</h2><ul>{"".join(f"<li>{e(x)}</li>" for x in items)}</ul>{foot}</section>')
        if i == 1:
            arrow = "<b>→</b>"
            out.append(f'<section class="s">{tag}<h2>작동 방식</h2><div class="flow">{arrow.join(f"<div>{e(x)}</div>" for x in d["flow"])}</div>{foot}</section>')
    return f'<!doctype html><html lang="ko"><head><meta charset="utf-8"><title>{e(d["title"])}</title><style>{CSS}</style></head><body>{"".join(out)}</body></html>'


def main(fonts: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for f in ("NotoSansKR-400.woff2", "NotoSansKR-700.woff2"):
        shutil.copy(fonts / f, out / f)
    for d in DECKS:
        (out / f"{d['key']}.html").write_text(deck_html(d), encoding="utf-8")
    manifest = [{k: d[k] for k in ("key", "causes", "title", "company", "one", "tags")} for d in DECKS]
    Path("data/demo_biz").mkdir(parents=True, exist_ok=True)
    Path("data/demo_biz/index.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
