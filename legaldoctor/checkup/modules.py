"""운영 단계 검진 모듈 정의. 사인 번호와 분류는 스타트업 부검보고서(구태언) 체계를 따른다.

모듈마다 다음을 정한다.
- 자료에서 뽑을 조항·사실의 범주(category)
- 범주별 기본 위험도, 진단 사슬의 어느 란에 해당하는지
- 범주별로 원문 대조를 꼭 해 볼 법령(고정 대조)과 조문을 좁힐 용어
- 창업자가 지금 할 수 있는 일
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Category:
    key: str
    label: str
    risk: str  # 높음 | 중간 | 낮음
    link: str  # 진단 사슬 란: 가 | 나 | 다 | 라 | Ⅱ
    anchors: list[tuple] = field(default_factory=list)  # (법령명, 조문을 좁힐 용어[, 조문 번호])
    action: str = ""
    grade_text: dict[str, str] | None = None  # 이 범주에서만 쓰는 판정 문구(모듈 기본값을 덮어씀)


@dataclass
class Module:
    key: str
    causes: list[int]  # 대비하는 사인 번호
    title: str
    input_label: str
    hint: str  # 탐색 엔진에 주는 검토 관점
    categories: list[Category]
    grade_text: dict[str, str]
    extract_guide: str
    kind: str = "law"  # law: 법령 원문 대조 | metrics: 숫자 계산과 점검 질문(경영 지표)

    def category(self, key: str) -> Category | None:
        return next((c for c in self.categories if c.key == key), None)


